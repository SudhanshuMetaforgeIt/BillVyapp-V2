const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

// 1. Analyze font weight classes
const classes = [
  'font-thin',       // 100
  'font-extralight', // 200
  'font-light',      // 300
  'font-normal',     // 400
  'font-medium',     // 500
  'font-semibold',   // 600
  'font-bold',       // 700
  'font-extrabold',  // 800
  'font-black',      // 900
];

const counts = {};
const fileMap = {};
classes.forEach(c => {
  counts[c] = 0;
  fileMap[c] = [];
});

function search(dir) {
  for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, f.name);
    if (f.isDirectory()) {
      if (['node_modules', '.next', '.git', '.performance'].includes(f.name)) continue;
      search(full);
    } else if (/\.(tsx?|css)$/.test(f.name)) {
      const text = fs.readFileSync(full, 'utf8');
      for (const c of classes) {
        let idx = 0;
        let foundInFile = 0;
        while ((idx = text.indexOf(c, idx)) !== -1) {
          const before = idx === 0 ? ' ' : text[idx - 1];
          const after = idx + c.length >= text.length ? ' ' : text[idx + c.length];
          const validBefore = /[\s"'`:([{]/.test(before);
          const validAfter = /[\s"'`:)\]}]/.test(after);
          if (validBefore && validAfter) {
            counts[c]++;
            foundInFile++;
          }
          idx += c.length;
        }
        if (foundInFile > 0) {
          fileMap[c].push({ file: path.relative('.', full), count: foundInFile });
        }
      }
    }
  }
}

search('.');

console.log('=== FONT WEIGHT USAGE AUDIT ===');
for (const [cls, count] of Object.entries(counts)) {
  const files = fileMap[cls].length;
  console.log(`${cls.padEnd(18)} : ${count.toString().padStart(4)} usages across ${files.toString().padStart(3)} files`);
}

// 2. Check font-light occurrences
if (counts['font-light'] > 0) {
  console.log('\n--- font-light occurrences ---');
  fileMap['font-light'].forEach(item => console.log(`  ${item.file}: ${item.count}`));
} else {
  console.log('\n--- font-light: 0 occurrences in entire codebase! ---');
}

