console.log('NOTE: Roboto (Classic) on Google Fonts ONLY offers weights: 100, 300, 400, 500, 700, 900.');
console.log('NOTE: Roboto does NOT have a native 600 (SemiBold) weight! When "600" is requested, Google Fonts either rejects it or falls back, or downloads synthetic/interpolated glyphs.');

// 4. CSS size loaded on every page
console.log('\n=== CSS LOADED ON EVERY PAGE ===');
const staticCssDir = path.join('.next', 'static', 'chunks');
if (fs.existsSync(staticCssDir)) {
  const cssFiles = fs.readdirSync(staticCssDir).filter(f => f.endsWith('.css'));
  cssFiles.forEach(f => {
    const full = path.join(staticCssDir, f);
    const buf = fs.readFileSync(full);
    const gz = zlib.gzipSync(buf);
    console.log(`CSS file: ${f} -> ${(buf.length / 1024).toFixed(1)} KiB minified, ${(gz.length / 1024).toFixed(1)} KiB gzip`);
  });
}

// 5. Inspect font-face rules in font CSS chunk
console.log('\n=== FONT-FACE RULES BREAKDOWN ===');
const fontCssFile = path.join('.next', 'static', 'chunks', '05fa2urimr_uk.css');
if (fs.existsSync(fontCssFile)) {
  const css = fs.readFileSync(fontCssFile, 'utf8');
  const fontFaces = css.split('@font-face').slice(1);
  console.log('Total @font-face rules generated by next/font/google:', fontFaces.length);
  const byWeight = {};
  fontFaces.forEach((f, i) => {
    const weight = f.match(/font-weight:([^;]+)/)?.[1] || 'unknown';
    const url = f.match(/url\(\.\.\/media\/([^)]+)\)/)?.[1] || 'inline';
    if (!byWeight[weight]) byWeight[weight] = [];
    byWeight[weight].push(url);
  });
  for (const [w, urls] of Object.entries(byWeight)) {
    console.log(`Weight ${w}: ${urls.length} subsets/ranges -> font files: ${[...new Set(urls)].join(', ')}`);
  }
}

